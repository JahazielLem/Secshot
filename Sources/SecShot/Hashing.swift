import CryptoKit
import Foundation

enum Hashing {
    static func sha256(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    static func sha256(fileAt url: URL) -> String {
        guard let data = try? Data(contentsOf: url) else { return "" }
        return sha256(data)
    }
}
